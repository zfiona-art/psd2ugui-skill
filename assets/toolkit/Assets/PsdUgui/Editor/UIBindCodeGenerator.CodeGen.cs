using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using PsdUgui;
using UnityEditor;
using UnityEngine;
using UnityEngine.UI;

/// <summary>
/// UI绑定代码生成器 - 代码生成模块
/// </summary>
namespace PsdUgui.Editor
{
public static partial class UIBindCodeGenerator
{
    /// <summary>
    /// 代码生成器：负责生成和更新 UI 脚本中的字段声明
    /// </summary>
    private static class CodeGen
    {
        // ───────────────────────────────────────────────
        //  骨架脚本生成
        // ───────────────────────────────────────────────

        /// <summary>
        /// 为全新脚本生成骨架代码（含字段声明）
        /// </summary>
        public static void GenerateSkeletonScript(
            string className,
            string scriptPath,
            CollectedNodes collected)
        {

            var sb = new StringBuilder();
            sb.AppendLine("using UnityEngine;");
            sb.AppendLine("using UnityEngine.UI;");
            sb.AppendLine("using PsdUgui;");
            sb.AppendLine();
            sb.AppendLine($"public class {className} : PsdUguiViewBase");
            sb.AppendLine("{");

            if (collected.MainNodes.Count > 0 || collected.ItemNodes.Count > 0)
            {
                sb.Append(GenerateFieldDeclarations(collected));
            }

            sb.AppendLine();
            sb.AppendLine();
            sb.AppendLine();
            sb.AppendLine("}");

            File.WriteAllText(scriptPath, sb.ToString(), new UTF8Encoding(true));
        }

        // ───────────────────────────────────────────────
        //  Item 脚本生成
        // ───────────────────────────────────────────────

        /// <summary>
        /// 为 item 节点生成独立脚本，支持增量更新 region
        /// </summary>
        public static bool GenerateItemScripts(CollectedNodes collected)
        {
            var anyChanged = false;
            var itemDir = "Assets/Scripts/View/Item";
            if (!Directory.Exists(itemDir))
                Directory.CreateDirectory(itemDir);

            foreach (var item in collected.ItemNodes)
            {
                var scriptPath = Path.Combine(itemDir, $"{item.ScriptName}.cs");

                // 构建 region 内的字段内容
                var fieldSb = new StringBuilder();
                foreach (var (name, compType) in item.ChildNodes)
                {
                    fieldSb.AppendLine($"    [SerializeField] private {compType.Name} {name};");
                }
                var fieldsContent = fieldSb.ToString();

                // 构建完整 region 块
                var regionSb = new StringBuilder();
                regionSb.AppendLine("    #region AutoGenerated UI Bindings");
                regionSb.AppendLine();
                if (!string.IsNullOrEmpty(fieldsContent))
                {
                    regionSb.Append(fieldsContent);
                }
                regionSb.AppendLine();
                regionSb.Append("    #endregion");
                var regionBlock = regionSb.ToString();

                // 脚本已存在则增量更新，否则生成骨架
                string finalContent;
                if (File.Exists(scriptPath))
                {
                    var existingContent = File.ReadAllText(scriptPath, Encoding.UTF8);
                    finalContent = PreserveLineEndings(InjectRegionBlock(existingContent, regionBlock), existingContent);
                    if (finalContent == existingContent)
                        continue; // 无变化，跳过
                }
                else
                {
                    finalContent = BuildItemSkeleton(item.ScriptName, item.ChildNodes, regionBlock);
                }

                File.WriteAllText(scriptPath, finalContent, new UTF8Encoding(true));
                Debug.Log($"生成 item 脚本: {scriptPath}");
                anyChanged = true;
            }

            return anyChanged;
        }

        /// <summary>
        /// 构建 item 脚本的骨架代码
        /// </summary>
        private static string BuildItemSkeleton(string scriptName, List<(string name, Type componentType)> childNodes, string regionBlock)
        {
            var sb = new StringBuilder();
            sb.AppendLine("using UnityEngine;");
            sb.AppendLine("using UnityEngine.UI;");
            sb.AppendLine();
            sb.AppendLine($"public class {scriptName} : MonoBehaviour");
            sb.AppendLine("{");
            sb.AppendLine(regionBlock);
            sb.AppendLine("}");

            return sb.ToString();
        }

        // ───────────────────────────────────────────────
        //  节点代码生成
        // ───────────────────────────────────────────────

        /// <summary>
        /// 生成或更新已有脚本的字段声明区域，返回是否有实际变化
        /// </summary>
        public static bool GenerateNode(GameObject root, PsdUguiViewBase uiBase)
        {
            var type = uiBase.GetType();

            var collected = PrefabAnalyzer.CollectAllNodes(root);
            if (collected.MainNodes.Count == 0 && collected.ItemNodes.Count == 0)
            {
                Debug.LogWarning("没有找到匹配前缀的子节点");
                return false;
            }

            // 先生成 item 脚本
            var itemScriptsChanged = GenerateItemScripts(collected);
            var generatedBlock = BuildRegionBlock(collected);

            var scriptPath = GetScriptPath(type);
            if (string.IsNullOrEmpty(scriptPath))
            {
                Debug.LogError($"找不到脚本路径: {type.Name}");
                return false;
            }

            var originalContent = File.ReadAllText(scriptPath, Encoding.UTF8);
            var scriptContent = InjectRegionBlock(originalContent, generatedBlock);
            scriptContent = PreserveLineEndings(EnsureUsings(scriptContent), originalContent);

            // 比较新旧内容，无变化则直接返回
            var mainScriptChanged = scriptContent != originalContent;
            if (!mainScriptChanged && !itemScriptsChanged)
            {
                Debug.Log($"脚本无变化，跳过生成: {scriptPath}");
                return false;
            }
            if (mainScriptChanged)
            {
                File.WriteAllText(scriptPath, scriptContent, new UTF8Encoding(true));
                Debug.Log($"重新生成组件代码: {scriptPath}");
            }
            
            // 脚本内容已变更，标记等待编译完成后 AutoBind
            QueuePendingPrefab(PendingNodeUIKey, root);
            RequestScriptRefresh();
            return true;
        }

        // ───────────────────────────────────────────────
        //  内部构建
        // ───────────────────────────────────────────────

        /// <summary>
        /// 构建 #region 代码块
        /// </summary>
        private static string BuildRegionBlock(CollectedNodes collected)
        {
            var sb = new StringBuilder();
            sb.AppendLine("    #region AutoGenerated UI Bindings");
            sb.AppendLine();

            // 普通字段
            foreach (var (name, compType) in collected.MainNodes)
            {
                sb.AppendLine($"    [SerializeField] private {compType.Name} {name};");
            }

            // item 字段
            foreach (var item in collected.ItemNodes)
            {
                sb.AppendLine($"    [SerializeField] private {item.ScriptName} {item.NodeName};");
            }

            sb.AppendLine();
            sb.Append("    #endregion");
            return sb.ToString();
        }

        private static string PreserveLineEndings(string content, string original)
        {
            string newline = original.Contains("\r\n") ? "\r\n" : "\n";
            return content.Replace("\r\n", "\n").Replace("\n", newline);
        }

        /// <summary>
        /// 将生成的代码块注入到脚本中
        /// </summary>
        private static string InjectRegionBlock(string scriptContent, string generatedBlock)
        {
            const string regionStartMarker = "    #region AutoGenerated UI Bindings";
            const string regionEndMarker   = "    #endregion";

            int regionStartIndex = scriptContent.IndexOf(regionStartMarker);
            if (regionStartIndex >= 0)
            {
                // 已有 region，替换内容
                int regionEndIndex = scriptContent.IndexOf(regionEndMarker, regionStartIndex + regionStartMarker.Length);
                if (regionEndIndex >= 0)
                {
                    return scriptContent.Substring(0, regionStartIndex)
                         + generatedBlock
                         + scriptContent.Substring(regionEndIndex + regionEndMarker.Length);
                }
            }
            else
            {
                // 没有 region，在 class 第一个 { 之后插入
                int firstBrace = scriptContent.IndexOf('{');
                if (firstBrace >= 0)
                {
                    return scriptContent.Insert(firstBrace + 1, "\n" + generatedBlock + "\n");
                }
            }

            return scriptContent;
        }

        /// <summary>
        /// 确保脚本包含必要的 using 语句
        /// </summary>
        private static string EnsureUsings(string content)
        {
            if (!content.Contains("using UnityEngine;"))
                content = "using UnityEngine;\n" + content;
            if (!content.Contains("using UnityEngine.UI;"))
                content = "using UnityEngine.UI;\n" + content;

            return content;
        }

        /// <summary>
        /// 生成字段声明字符串
        /// </summary>
        private static string GenerateFieldDeclarations(CollectedNodes collected)
        {
            if (collected.MainNodes.Count == 0 && collected.ItemNodes.Count == 0)
                return "";

            var sb = new StringBuilder();
            sb.AppendLine("    #region AutoGenerated UI Bindings");
            sb.AppendLine();

            // 普通字段
            foreach (var (name, compType) in collected.MainNodes)
            {
                sb.AppendLine($"    [SerializeField] private {compType.Name} {name};");
            }

            // item 字段
            foreach (var item in collected.ItemNodes)
            {
                sb.AppendLine($"    [SerializeField] private {item.ScriptName} {item.NodeName};");
            }

            sb.AppendLine();
            sb.Append("    #endregion");
            return sb.ToString();
        }

    }
}

}
